r"""Conforming subdivision of a simploidal Bézier space.

Splitting a factor edge ``(i, j)`` of a cell at ``s`` bisects that factor simplex, so the cell becomes two
simploids of the same type.  To keep the space conforming, every cell sharing a piece of the split edge
direction is split too: the marked factor edges form the equivalence class generated by

* a factor edge of a simploid and the corresponding factor edge of each of its faces, and
* for a degenerate face, the factor edge of its base that the face's factor edge maps to (none if the
  degeneracy collapses it).

These relations preserve the order of the vertices within a factor, so every edge of the class is split at
the same ``s`` in a consistent direction.  Each simploid is subdivided by bisecting its marked edges in
lexicographic order of the original vertex pairs, factor by factor; this commutes with taking faces, so
shared faces are subdivided identically.  De Casteljau subdivision is affine in the barycentric coordinates
and commutes with degeneracy maps, so the subdivision of a degenerate face is the image of the subdivision
of its base, and the result is again a simploidal set.

The refined set is assembled directly: every piece is identified by a canonical key, the original
non-degenerate simploid whose relative interior contains it together with the exact (rational) barycentric
coordinates of its vertices there, and pieces with equal keys are the same simploid.  A piece of a
degenerate face is the degeneracy of the piece of the base it maps onto.
"""

from collections.abc import Iterator, Sequence
from fractions import Fraction

import torch

from torch_bsf._kernels._splitting import split
from torch_bsf._kernels.bezier import BezierSimploid
from torch_bsf._kernels.combinatorics import DegeneracyMap
from torch_bsf._kernels.sets import Simploid, SimploidalSet, _canonical

Point = tuple[Fraction, ...]
#: The vertices of a piece in each factor of its support, as exact barycentric points of that factor.
Lists = tuple[tuple[Point, ...], ...]
#: A factor edge ``(simploid, factor, i, j)`` with ``i < j``.
FactorEdge = tuple[Simploid, int, int, int]


def _unit(n: int, k: int) -> Point:
    return tuple(Fraction(int(v == k)) for v in range(n))


def _face_factor(simploid_type: tuple[int, ...], x: int, k: int) -> int:
    """The index in face ``(x, *)`` of factor ``k != x`` (or of ``k == x`` when that factor survives)."""
    return k - 1 if simploid_type[x] == 1 and k > x else k


def _related(fe: FactorEdge) -> list[FactorEdge]:
    """The factor edges of the faces of ``fe[0]`` that ``fe`` restricts to, mapped through degeneracies."""
    s, k, i, j = fe
    out = []
    for (x, v), f in s.faces():
        if x == k and v in (i, j):
            continue
        k2 = _face_factor(s.simploid_type, x, k)
        i2, j2 = (i - (i > v), j - (j > v)) if x == k else (i, j)
        if not f.is_degenerate:
            out.append((f, k2, i2, j2))
            continue
        src, g = f.degeneracy_map[k2]
        if src >= 0 and g[i2] != g[j2]:
            out.append((f.base, src, g[i2], g[j2]))
    return out


def marked_edges(simploids: Sequence[Simploid], start: FactorEdge) -> dict[Simploid, list[tuple[int, int, int]]]:
    """The class of factor edges to split with ``start``, grouped by simploid in lexicographic order."""
    parent: dict[FactorEdge, FactorEdge] = {}

    def find(x: FactorEdge) -> FactorEdge:
        root = x
        while parent.get(root, root) != root:
            root = parent[root]
        parent[x] = root
        return root

    for fe in (fe for s in simploids for fe in _factor_edges(s)):
        for g in _related(fe):
            parent[find(g)] = find(fe)
    root = find(start)
    marks: dict[Simploid, set[tuple[int, int, int]]] = {}
    for fe in [*parent, start]:
        if find(fe) == root:
            marks.setdefault(fe[0], set()).add(fe[1:])
    return {s: sorted(m) for s, m in marks.items()}


def _factor_edges(s: Simploid) -> Iterator[FactorEdge]:
    for k, a in enumerate(s.simploid_type):
        for i in range(a + 1):
            for j in range(i + 1, a + 1):
                yield s, k, i, j


def _bisect(lists: Lists, marks: Sequence[tuple[int, int, int]], s: Fraction) -> list[tuple[Lists, list[int]]]:
    """Pieces of a simploid with vertices ``lists``, with the indices of the splits taking each one's side.

    Each marked edge ``(k, i, j)`` is bisected in the pieces that still contain both original vertices ``i``
    and ``j`` of factor ``k`` (at slots ``i`` and ``j``): piece A replaces slot ``j`` by the new point, piece
    B replaces slot ``i``.  The second item of each result has one entry per mark: ``0`` for A, ``1`` for B
    and ``-1`` if the piece was not split there.
    """
    pieces: list[tuple[Lists, list[int]]] = [(lists, [])]
    for k, i, j in marks:
        a = len(lists[k][0])
        vi, vj = _unit(a, i), _unit(a, j)
        m = tuple((1 - s) * p + s * q for p, q in zip(vi, vj, strict=True))
        out = []
        for piece, path in pieces:
            if piece[k][i] == vi and piece[k][j] == vj:
                for slot, side in ((j, 0), (i, 1)):
                    factor = piece[k][:slot] + (m,) + piece[k][slot + 1 :]
                    out.append((piece[:k] + (factor,) + piece[k + 1 :], path + [side]))
            else:
                out.append((piece, path + [-1]))
        pieces = out
    return pieces


def _full(simploid: Simploid) -> Lists:
    return tuple(tuple(_unit(a + 1, v) for v in range(a + 1)) for a in simploid.simploid_type)


class Refinement:
    """The refined simploidal set of a conforming subdivision (see the module docstring)."""

    def __init__(self, simploids: Sequence[Simploid], start: FactorEdge, s: Fraction):
        self.s = s
        self.marks = marked_edges(simploids, start)
        self.domain = SimploidalSet()
        self._made: dict[tuple[Simploid, Lists], Simploid] = {}
        self._pieces: dict[Simploid, list[tuple[Lists, list[int]]]] = {}
        #: The refined simploid of each top-dimensional piece of each original simploid, in piece order.
        self.tops: dict[Simploid, list[Simploid]] = {}
        #: The original simploid whose relative interior contains each refined non-degenerate simploid.
        self.support: dict[Simploid, Simploid] = {}
        for sigma in simploids:
            self.tops[sigma] = [self._make(sigma, lists) for lists, _ in self.pieces(sigma)]
        self.domain._add(list(self._made.values()))

    def pieces(self, sigma: Simploid) -> list[tuple[Lists, list[int]]]:
        """The top-dimensional pieces of an original non-degenerate simploid."""
        if sigma not in self._pieces:
            self._pieces[sigma] = _bisect(_full(sigma), self.marks.get(sigma, []), self.s)
        return self._pieces[sigma]

    def _make(self, sigma: Simploid, lists: Lists) -> Simploid:
        """The refined non-degenerate simploid with canonical key ``(sigma, lists)``."""
        key = (sigma, lists)
        made = self._made.get(key)
        if made is not None:
            return made
        made = Simploid(tuple(len(d) - 1 for d in lists if len(d) > 1))
        self._made[key] = made
        self.support[made] = sigma
        q = 0
        for x, d in enumerate(lists):
            if len(d) == 1:
                continue
            for v in range(len(d)):
                face = lists[:x] + (d[:v] + d[v + 1 :],) + lists[x + 1 :]
                made._faces[(q, v)] = self.resolve(sigma, face)
            q += 1
        return made

    def resolve(self, sigma: Simploid, lists: Lists) -> Simploid:
        """The refined simploid spanned by points of ``sigma`` (repeated points give a degeneracy)."""
        # Track, for every factor of ``lists``, the factor of the current simploid it lies in and its points.
        entries: list[tuple[int | None, tuple[Point, ...]]] = [(x, d) for x, d in enumerate(lists)]
        current = sigma
        while True:
            reduced = self._reduce(current, entries)
            if reduced is None:
                break
            current, entries = reduced
        support = [next(d for x, d in entries if x == y) for y in range(current.length)]
        distinct = tuple(tuple(dict.fromkeys(d)) for d in support)
        self._check_piece(current, distinct)
        positions = [y for y, d in enumerate(distinct) if len(d) > 1]
        dmap: list[tuple[int, tuple[int, ...]]] = []
        for (x, d), original in zip(entries, lists, strict=True):
            if len(original) == 1:
                continue
            if x is None or len(distinct[x]) == 1:
                dmap.append((-1, (0,) * len(original)))
                continue
            g = tuple(distinct[x].index(p) for p in d)
            assert all(a <= b for a, b in zip(g, g[1:], strict=False)), "a degeneracy must preserve vertex order"
            dmap.append((positions.index(x), g))
        return _canonical(self._make(current, distinct), tuple(dmap))

    @staticmethod
    def _reduce(
        sigma: Simploid, entries: list[tuple[int | None, tuple[Point, ...]]]
    ) -> tuple[Simploid, list[tuple[int | None, tuple[Point, ...]]]] | None:
        """Move points lying in a proper face of ``sigma`` to that face (and to its base if degenerate)."""
        for x, a in enumerate(sigma.simploid_type):
            d = next(d for y, d in entries if y == x)
            v = next((v for v in range(a + 1) if all(p[v] == 0 for p in d)), None)
            if v is None:
                continue
            f = sigma.face(x, v)
            moved: list[tuple[int | None, tuple[Point, ...]]] = []
            for y, points in entries:
                if y == x:
                    points = tuple(p[:v] + p[v + 1 :] for p in points)
                    moved.append((None if a == 1 else x, points))
                elif y is not None and a == 1 and y > x:
                    moved.append((y - 1, points))
                else:
                    moved.append((y, points))
            if not f.is_degenerate:
                return f, moved
            return f.base, [_push(f.degeneracy_map, f.base, y, points) for y, points in moved]
        return None

    def _check_piece(self, sigma: Simploid, distinct: Lists) -> None:
        """Every refined simploid must be a face of a piece of its support (the subdivision is conforming)."""
        pieces = [lists for lists, _ in self.pieces(sigma)]
        assert any(all(_subsequence(d, piece[x]) for x, d in enumerate(distinct)) for piece in pieces), (
            "the subdivision is not conforming"
        )


def _push(
    dmap: DegeneracyMap, base: Simploid, y: int | None, points: tuple[Point, ...]
) -> tuple[int | None, tuple[Point, ...]]:
    """Map points of factor ``y`` of a degenerate simploid to the factor of its base it comes from."""
    if y is None:
        return None, points
    src, g = dmap[y]
    if src < 0:
        return None, points
    n = base.simploid_type[src] + 1
    return src, tuple(tuple(sum((p[u] for u in range(len(g)) if g[u] == w), Fraction(0)) for w in range(n)) for p in points)


def _subsequence(d: tuple[Point, ...], piece: tuple[Point, ...]) -> bool:
    it = iter(piece)
    return all(p in it for p in d)


def split_nets(
    net: BezierSimploid,
    marks: Sequence[tuple[int, int, int]],
    s: float,
    paths: Sequence[list[int]],
    reverse: bool = False,
) -> list[torch.Tensor]:
    """Control nets of the pieces of a Bézier simploid, following the bisection paths of :func:`_bisect`.

    Each marked edge ``(k, i, j)`` is split at ``s`` from ``i`` to ``j``, or from ``j`` to ``i`` if ``reverse``.
    The reversed split is computed as such rather than as a split at ``1 - s``, which rounds to one for tiny ``s``.
    """
    nets: dict[tuple[int, ...], BezierSimploid] = {(): net}
    for depth, (k, i, j) in enumerate(marks):
        out: dict[tuple[int, ...], BezierSimploid] = {}
        for path, piece in nets.items():
            if not any(p[depth] >= 0 for p in paths if tuple(p[:depth]) == path):
                out[path + (-1,)] = piece
            elif reverse:
                out[path + (1,)], out[path + (0,)] = split(piece, j, i, s, factor=k)
            else:
                out[path + (0,)], out[path + (1,)] = split(piece, i, j, s, factor=k)
        nets = out
    return [nets[tuple(p)].control_points for p in paths]


def _project(points: torch.Tensor, simploid_type: Sequence[int]) -> torch.Tensor:
    """Clamp barycentric rows to be nonnegative and to sum to one on every factor."""
    out = points.clamp_min(0)
    offset = 0
    for a in simploid_type:
        block = out[:, offset : offset + a + 1]
        out[:, offset : offset + a + 1] = block / block.sum(dim=1, keepdim=True)
        offset += a + 1
    return out


def locate(points: torch.Tensor, simploid_type: Sequence[int], pieces: Sequence[Lists]) -> tuple[torch.Tensor, torch.Tensor]:
    """The piece containing each point (barycentric rows of a simploid) and its coordinates there.

    The points are first projected onto the simploid, so a point within the drift that point validation accepts
    is located too.  The pieces cover the simploid, so the piece whose smallest coordinate is largest contains the
    point up to rounding; its coordinates are projected as well.
    """
    points = _project(points, simploid_type)
    n = len(points)
    best = torch.zeros(n, dtype=torch.long)
    coords = torch.zeros_like(points)
    margin = torch.full((n,), -float("inf"), dtype=points.dtype)
    for k, lists in enumerate(pieces):
        blocks, offset, worst = [points[:, :0]], 0, torch.full((n,), float("inf"), dtype=points.dtype)
        for a, d in zip(simploid_type, lists, strict=True):
            vertices = torch.tensor([[float(c) for c in p] for p in d], dtype=points.dtype)  # (a + 1, a + 1)
            lam = torch.linalg.solve(vertices.T, points[:, offset : offset + a + 1].T).T
            blocks.append(lam)
            worst = torch.minimum(worst, lam.min(dim=1).values)
            offset += a + 1
        better = worst > margin
        margin = torch.where(better, worst, margin)
        best[better] = k
        coords[better] = torch.cat(blocks, dim=1)[better]
    return best, _project(coords, simploid_type)


def nodes_of(
    space_cells: Sequence[tuple[int, ...]], topology: Sequence[tuple[tuple[int, int, int, DegeneracyMap], ...]]
) -> tuple[list[Simploid], dict[Simploid, int]]:
    """Rebuild the non-degenerate simploids of a compiled space, with the cell ID of each that is a cell."""
    if not topology:
        domain = SimploidalSet()
        top = domain.add_simploid(space_cells[0])
        return domain.simploids(), {top: 0}
    nodes = [Simploid(dimensions) for dimensions in space_cells]
    for node, faces in zip(nodes, topology, strict=True):
        for i, j, base, mapping in faces:
            node._faces[(i, j)] = _canonical(nodes[base], mapping)
    return nodes, {node: k for k, node in enumerate(nodes)}


